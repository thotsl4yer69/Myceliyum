const fs = require('node:fs');
const path = require('node:path');

function buildCatalogue(records, safetySource) {
  const safety = Object.fromEntries([...safetySource.matchAll(/"([^"]+)" to Edibility\.([A-Z]+)/g)].map(m => [m[1], m[2]]));
  const labels = { DEADLY: ['deadly', 'Deadly'], POISONOUS: ['toxic', 'Poisonous'], PSYCHOACTIVE: ['psy', 'Psychoactive'], EDIBLE: ['reference', 'Reference only'], INEDIBLE: ['reference', 'Reference only'], UNKNOWN: ['reference', 'Unverified'] };
  return records.map(s => {
    const [status, statusLabel] = labels[safety[s.id] || 'UNKNOWN'];
    return {
      id: s.id, sci: s.scientificName, com: s.commonNames[0] || s.scientificName,
      genus: s.genus, family: s.family, habitat: s.habitatTypes.join(' · '),
      season: [s.seasonStart, s.seasonEnd], spore: s.sporeColor, sporeHex: '#a49b83',
      status, statusLabel, tags: [status], capHex: '#a49b83',
      marks: [s.capDescription, s.gillDescription, s.stemDescription].filter(Boolean).join(' '),
      look: s.lookAlikes.join(' · '),
      source: 'https://github.com/thotsl4yer69/Myceliyum/blob/main/app/src/main/assets/species.json'
    };
  });
}
function renderCatalogue(records, safety) {
  return '// Generated by scripts/sync_catalogue.cjs from the Android catalogue.\nconst SPECIES = ' + JSON.stringify(buildCatalogue(records, safety), null, 2) + ';\n';
}
module.exports = { buildCatalogue, renderCatalogue };
if (require.main === module) {
  const root = path.resolve(__dirname, '..');
  const result = renderCatalogue(
    JSON.parse(fs.readFileSync(path.join(root, 'app/src/main/assets/species.json'), 'utf8')),
    fs.readFileSync(path.join(root, 'app/src/main/java/com/example/util/FungiSafety.kt'), 'utf8')
  );
  const target = path.join(root, 'docs/catalogue.js');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== result) throw new Error('Run node scripts/sync_catalogue.cjs to synchronize the website catalogue');
  } else fs.writeFileSync(target, result);
}
