const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {selectVerifiedRelease} = require('../docs/release.js');
const {renderCatalogue, buildCatalogue} = require('../scripts/sync_catalogue.cjs');

const ref = 'https://github.com/thotsl4yer69/Myceliyum/releases/download/latest/app-debug.apk';
const manifest = {versionCode:7201, versionName:'7.2', sourceCommit:'b'.repeat(40),
  sha256:'a'.repeat(64), apkUrl:ref};
function release(changes = {}) {
  const values = {...manifest,...changes};
  return {body:'MYCELIYUMS-RELEASE ' + JSON.stringify(values),
    target_commitish:manifest.sourceCommit, draft:false, prerelease:false,
    assets:[{browser_download_url:ref,state:'uploaded',size:100000,digest:'sha256:' + manifest.sha256}]};
}
test('valid version, source, uploaded size and SHA256 enable one verified download', () => {
  assert.deepEqual(selectVerifiedRelease(release()),manifest);
});
test('draft, prerelease and legacy entries never activate a download', () => {
  assert.equal(selectVerifiedRelease({...release(),draft:true}),null);
  assert.equal(selectVerifiedRelease({...release(),prerelease:true}),null);
  assert.equal(selectVerifiedRelease({body:'Older release',assets:[]}),null);
});
test('reject mismatched binary digest and empty upload', () => {
  assert.equal(selectVerifiedRelease(release({sha256:'c'.repeat(64)})),null);
  assert.equal(selectVerifiedRelease({...release(),assets:[{browser_download_url:ref,size:0,state:'uploaded',digest:'sha256:' + manifest.sha256}]}),null);
});
test('reject mismatched source and untrusted download locations', () => {
  assert.equal(selectVerifiedRelease(release({sourceCommit:'c'.repeat(40)})),null);
  assert.equal(selectVerifiedRelease(release({apkUrl:'https://example.net/untrusted.apk'})),null);
  assert.equal(selectVerifiedRelease(release({versionCode:5})),null);
});
test('website catalogue is generated byte-for-byte from Android source', () => {
  const android = JSON.parse(fs.readFileSync('app/src/main/assets/species.json','utf8'));
  const safety = fs.readFileSync('app/src/main/java/com/example/util/FungiSafety.kt','utf8');
  assert.equal(fs.readFileSync('docs/catalogue.js','utf8'),renderCatalogue(android,safety));
  assert.equal(buildCatalogue(android,safety).length,android.length);
});
test('website ships verified release gate and catalogue in correct order', () => {
  const html = fs.readFileSync('docs/index.html','utf8');
  const a = html.indexOf('src="catalogue.js"');
  const b = html.indexOf('src="release.js"');
  const c = html.indexOf('src="app.js"');
  assert.ok(a > 0 && b > a && c > b);
  assert.match(html,/data-release-download/);
  assert.match(html,/releaseStatus/);
});
